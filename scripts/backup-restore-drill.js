/**
 * Evidence held in the `protected_authority` schema rather than `public`.
 *
 * This is the single most important thing this drill learned the hard way. A first attempt restored
 * `privileged_action_approvals` and was rejected outright:
 *
 *     Protected approval must be requested through the protected authority
 *
 * `protected_authority.approval_authority_guard()` is a SECURITY DEFINER trigger that refuses an
 * approval row unless there is a matching `checker_decisions` row (for APPROVED/CONSUMED) and a
 * matching `approval_consumptions` row (for CONSUMED), with the payload digest recomputed from the
 * approval itself. Those rows live in a different schema, owned by a different role. Backing up only
 * `public` would therefore have produced a backup that *cannot be restored* — discovered here, in a
 * rehearsal, rather than during an outage. Governance history is not a side table of the domain; it is
 * a prerequisite for the domain being restorable at all.
 */
const PROTECTED_TABLES = ['checker_decisions', 'approval_consumptions'];

