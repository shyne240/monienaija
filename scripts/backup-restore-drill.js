#!/usr/bin/env node
/**
 * Backup and restore rehearsal — every financial category the mission names.
 *
 * ## Why this is not pg_dump
 *
 * `pg_dump`, `pg_restore` and `psql` are absent from this environment. Rather than declare the
 * requirement unmet, this performs the same *operation* over the wire: read every row of every relevant
 * table, rebuild the schema from the real migration chain, load the rows back, and verify. What differs
 * from a production backup is durability and policy — off-site storage, encryption at rest, retention,
 * point-in-time recovery. Those are infrastructure decisions and are listed as outstanding rather than
 * simulated.
 *
 * ## What it found
 *
 * A backup that has never been restored is not recovery, and writing this one proved the point. Each
 * finding below came from a restore attempt that actually failed, not from inspection:
 *
 *  1. **JSON silently rounds money.** `json_agg` renders `numeric` as a bare JSON number, which
 *     `JSON.parse` turns into a double: `12345678901234567890` becomes `...567000`. The reader projects
 *     `numeric`/`bigint` through `::text` so exact decimal strings travel instead.
 *
 *  2. **Deferred ledger constraints need one transaction.** `ledger_journal_must_balance` and
 *     `ledger_lines_must_balance_journal` are DEFERRABLE INITIALLY DEFERRED — they fire at COMMIT. Under
 *     autocommit a journal cannot be inserted before its balancing lines, so the backup would look
 *     un-restorable while being perfectly good.
 *
 *  3. **Governance evidence lives outside `public`.** Restoring approvals failed with "Protected approval
 *     must be requested through the protected authority": the guard requires matching rows in
 *     `protected_authority.checker_decisions` / `approval_consumptions`. A `public`-only backup cannot be
 *     restored at all. Those two tables are now backed up and restored.
 *
 *  4. **Some tables are derived and cannot be copied.** `governed_institution_lifecycle_executions`
 *     refuses INSERT unless `pg_trigger_depth() >= 2`; `kyc_evaluation_refresh` is a work queue that the
 *     KYC triggers repopulate during the restore. Both are regenerated by the transition that produces
 *     them, so copying them is both impossible and wrong.
 *
 *  5. **Four ledger accounts are provisioned non-deterministically.** `CASH_TO_CASH-UNCLAIMED-NGN`,
 *     `AGENT_FUNDING_POOL-NGN`, `FINANCE-FEE_REVENUE-NGN` and `FINANCE-VAT_PAYABLE-NGN` are inserted with
 *     `gen_random_uuid()`, verified to differ across two independently migrated databases. Ledger lines
 *     in a production backup will point at the *source's* ids. A restore into a freshly migrated database
 *     either fails the foreign key or — worse, and silently — re-attaches those lines to a different
 *     account object with the same code. This drill resolves every such collision up front, rewrites the
 *     references deliberately, and names each one in its output and report.
 *
 *  6. **jsonb `[]` was becoming `{}`.** A JS array bound by node-postgres is serialized as a PostgreSQL
 *     array literal, which the jsonb input function reads as an empty object. `scopes: []` on a role
 *     assignment would have restored as `scopes: {}`. JSON columns are now explicitly stringified.
 *
 * ## How the guards are handled, and why that is not a shortcut
 *
 * Guards are written for operations, not restores. `approval_authority_guard` requires
 * `expires_at > clock_timestamp()`, which a genuine historic approval can never satisfy; the execution
 * evidence guard requires trigger depth. Postgres draws the same line itself: `pg_restore
 * --disable-triggers` exists so a restore reproduces *state* without re-running *policy*. This drill does
 * the same (`session_replication_role = replica`) and pays for it by re-establishing integrity from the
 * data rather than trusting the guards it just bypassed:
 *
 *   - every backed-up row compared against the live source by server-computed fingerprint (not against
 *     the serialized file, where a `timestamptz` differs from a `Date` and produces a flood of false
 *     failures);
 *   - a full foreign-key sweep over every FK in the restored set;
 *   - every journal balances, and the ledger's total debit and line count are unchanged;
 *   - no ledger line is orphaned.
 *
 * ## Two runs, eleven categories
 *
 * No single available fixture populates all eleven categories at once. The drill therefore reports how
 * many categories actually carried data, and names the ones that did not, rather than implying coverage
 * it did not exercise:
 *
 *   mn_it_fcinit_g19drill_1806328    2030 rows / 50 tables — all but reconciliation_exceptions
 *   mn_it_a3dfloat_g19float_1807347   984 rows / 50 tables — all but financial_commitments
 *
 * Between them every category is restored and verified. A single run with a fixture that seeds all
 * eleven remains outstanding.
 *
 * Usage:
 *   PG_TEST_CONFIRM_DISPOSABLE_CLUSTER=yes node scripts/backup-restore-drill.js [--keep]
 *
 * Requires a role permitted to set `session_replication_role` (a superuser), which narrows who may
 * perform a restore. That is recorded as a deployment decision, not assumed.
 */
