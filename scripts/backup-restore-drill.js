function log(message) {
  process.stdout.write(`${message}\n`);
}

function requireDisposableCluster() {
  if (process.env.PG_TEST_CONFIRM_DISPOSABLE_CLUSTER !== 'yes') {
    throw new Error(
      'Refusing to run: this script creates and drops a database. Set ' +
        'PG_TEST_CONFIRM_DISPOSABLE_CLUSTER=yes only against a disposable cluster.',
    );
  }
}

async function connect(database) {
  const client = new Client({ ...ADMIN, database });
  await client.connect();
  return client;
}

/**
 * Reads every row of a table losslessly.
 *
 * `numeric` and `bigint` are projected through `::text` because JSON would otherwise carry them as
 * doubles and silently round them — see the header. Everything else keeps its natural representation.
 */
function splitQualified(ref) {
  const [schema, name] = ref.includes('.') ? ref.split('.') : ['public', ref];
  return { schema, name };
}

async function readTable(client, ref) {
  const { schema, name } = splitQualified(ref);
  const { rows: columnRows } = await client.query(
    `SELECT column_name, data_type FROM information_schema.columns
      WHERE table_schema=$1 AND table_name=$2
      ORDER BY ordinal_position`,
    [schema, name],
  );
  if (columnRows.length === 0) throw new Error(`table ${ref} does not exist`);

  const projection = columnRows
    .map(({ column_name: name, data_type: type }) =>
      ['numeric', 'bigint'].includes(type) ? `"${name}"::text AS "${name}"` : `"${name}"`,
    )
    .join(',');

  const { rows } = await client.query(
    `SELECT COALESCE(json_agg(x), '[]'::json) AS rows FROM (SELECT ${projection} FROM "${schema}"."${name}") x`,
  );
  return { columns: columnRows.map((c) => c.column_name), rows: rows[0].rows };
}

/** Writes one table to a JSON file and returns its byte length. */
function writeTable(dir, table, payload) {
  const buffer = Buffer.from(JSON.stringify(payload));
  fs.writeFileSync(path.join(dir, `${table.replace(/\./g, '__')}.json`), buffer);
  return buffer.length;
}

/**
 * Inserts rows positionally so PostgreSQL casts the text-encoded numerics back exactly.
 *
 * Every write happens inside one transaction, and that is a requirement rather than a preference.
 * `ledger_journals.ledger_journal_must_balance` and `ledger_lines.ledger_lines_must_balance_journal`
 * are **deferrable, initially deferred** constraints: they fire at COMMIT, not per row. A journal is
 * therefore inserted before the lines that balance it, and only becomes valid at the end. Under
 * autocommit each statement is its own transaction, so the journal insert would be rejected for being
 * unbalanced and the restore could never succeed — the backup would look unusable while the data was
 * in fact perfectly restorable.
 *
 * The single transaction also means a failure halfway leaves an empty database rather than a partial
 * one, so a failed restore cannot be mistaken for a complete one.
 */
/**
 * Compares a backed-up row with the row already in the target, ignoring provisioning timestamps.
 *
 * `created_at`/`updated_at` on a migration-seeded row are set when the migration ran, so they
 * necessarily differ between the source and the restore target — by design, not by corruption. Every
 * other column must match exactly. The exemption is limited to those two names rather than "any column
 * ending in _at", so that a domain timestamp (a settlement time, a licence expiry) cannot hide a
 * difference behind this check.
 */
const PROVISIONING_TIMESTAMPS = new Set(['created_at', 'updated_at', 'inserted_at']);

function sameExceptTimestamps(columns, existing, row) {
  return columns.every(
    (column) =>
      PROVISIONING_TIMESTAMPS.has(column) || String(existing[column]) === String(row[column]),
  );
}

/**
 * Rewrites references to identifiers that changed on restore.
 *
 * `referencingColumns` is `[{ column }]` for the table about to load; every value equal to a remapped
 * source id is replaced with the target id. Applied at load time so dependent rows never point at an
 * identifier that does not exist — the alternative, repairing afterwards, would briefly create a
 * database whose ledger lines referenced nothing.
 */
function applyRemaps(ref, rows, referencingColumns) {
  if (idRemaps.size === 0 || referencingColumns.length === 0) return { rows, rewritten: 0 };
  const bySource = new Map();
  for (const remap of idRemaps.values()) bySource.set(remap.sourceId, remap.targetId);
  let rewritten = 0;
  const out = rows.map((row) => {
    let copy = null;
    for (const column of referencingColumns) {
      const value = row[column];
      if (value !== null && value !== undefined && bySource.has(String(value))) {
        copy = copy ?? { ...row };
        copy[column] = bySource.get(String(value));
        rewritten += 1;
      }
    }
    return copy ?? row;
  });
  return { rows: out, rewritten };
}

/**
 * Prepares a value for binding, JSON-encoding `jsonb`/`json` columns.
 *
 * This is not a nicety. `json_agg` returns a jsonb value as a parsed JS value, so a jsonb column holding
 * `[]` comes back as a JS array. `node-postgres` serializes a JS array as a *PostgreSQL array literal*
 * (`{}`), which the jsonb input function then reads as an empty JSON **object**. The array silently
 * becomes `{}` — and it is only visible because the verification compares the two databases field by
 * field. Restoring `scopes: []` as `scopes: {}` on a role assignment changes what the row means.
 *
 * Only object/array values for JSON-typed columns are stringified; everything else (including a jsonb
 * value that is a bare string or number) is passed through as the driver expects.
 */
function bindValue(value, isJsonColumn) {
  if (!isJsonColumn) return value;
  if (value === null || value === undefined) return value;
  if (typeof value === 'object') return JSON.stringify(value);
  return value;
}

async function restoreTable(client, table, columns, rows) {
  const { schema: tableSchema, name: tableName } = splitQualified(table);
  const { rows: jsonColumnRows } = await client.query(
    `SELECT column_name FROM information_schema.columns
      WHERE table_schema = $1 AND table_name = $2 AND data_type IN ('jsonb', 'json')`,
    [tableSchema, tableName],
  );
  const jsonColumns = new Set(jsonColumnRows.map((r) => r.column_name));
  const quoted = columns.map((c) => `"${c}"`).join(',');
  const placeholders = columns.map((_, index) => `$${index + 1}`).join(',');
  const target = table.includes('.')
    ? `"${table.split('.')[0]}"."${table.split('.')[1]}"`
    : `"${table}"`;
  const sql = `INSERT INTO ${target} (${quoted}) VALUES (${placeholders})`;
  let skippedPreProvisioned = 0;

  for (const row of rows) {
    // Each row gets its own savepoint so a caught conflict cannot poison the surrounding transaction.
    // Without this, the *next* statement fails with "current transaction is aborted" and the original
    // cause is buried — which is exactly what happened while this drill was being written.
    await client.query('SAVEPOINT restore_row');
    try {
      await client.query(
        sql,
        columns.map((column) => bindValue(row[column], jsonColumns.has(column))),
      );
      await client.query('RELEASE SAVEPOINT restore_row');
    } catch (error) {
      await client.query('ROLLBACK TO SAVEPOINT restore_row');
      await client.query('RELEASE SAVEPOINT restore_row');

      /*
       * A handful of rows are *schema*, not data: the migrations seed fixed ledger accounts (the
       * payment settlement/suspense trio at `00000000-0000-4000-8000-00000000020{1,2,3}`, the
       * commercial accounting families) with stable identifiers. A freshly migrated database already
       * contains them, so restoring the backed-up copy collides on a unique constraint.
       *
       * Skipping is only safe because those rows are recreated by the migration chain, and because the
       * check is narrow: the pre-existing row must be identical in every column except its provisioning
       * timestamps. Anything else — a genuinely duplicated business row, or a system account whose
       * values have drifted — is re-raised, so this cannot quietly hide a real restore defect.
       */
      if (error.code !== '23505') throw error;
      const constraint = error.constraint ?? '';
      const keyColumn = /_pkey$/.test(constraint) ? 'id' : /code/.test(constraint) ? 'code' : 'id';
      if (row[keyColumn] === undefined) throw error;
      const existing = await client.query(`SELECT * FROM ${target} WHERE "${keyColumn}" = $1`, [
        row[keyColumn],
      ]);
      if (existing.rows.length === 0) throw error;

      /*
       * A conflict on `code` rather than `id` means the migration chain provisioned a row with the same
       * business key but a *different* identifier. That is a real defect this drill just surfaced:
       * `1785753600057-CreateCashToCashTransfers.ts` seeds 'CASH_TO_CASH-UNCLAIMED-NGN' with
       * `gen_random_uuid()`, so every freshly migrated database gets a different id for the same account.
       * Any backup that captures ledger lines against the source's id will restore them attached to a
       * different account object than the one it recorded — silently, if nothing checks.
       *
       * Rather than fail here (the rows are otherwise identical and the data is genuinely restorable),
       * the incident is recorded and the *target's* id is adopted. The post-restore verification then
       * re-resolves every reference that was rewritten this way and reports them, so a recovery cannot
       * quietly remap ledger identities without anyone noticing.
       */
      if (keyColumn === 'code') {
        const diffs = columns.filter(
          (c) =>
            !PROVISIONING_TIMESTAMPS.has(c) &&
            c !== 'id' &&
            String(existing.rows[0][c]) !== String(row[c]),
        );
        if (diffs.length > 0) {
          throw new Error(
            `${table}: existing row ${row[keyColumn]} conflicts but differs in ${diffs.join(', ')}`,
          );
        }
        // The mapping itself was resolved before the load began (see the divergence sweep), which is
        // what allows dependent rows to be re-pointed as they are written rather than repaired after.
        // Recording it again here would overwrite that record with one lacking the table name.
        skippedPreProvisioned += 1;
        continue;
      }

      if (!sameExceptTimestamps(columns, existing.rows[0], row)) {
        const diffs = columns.filter(
          (c) => !PROVISIONING_TIMESTAMPS.has(c) && String(existing.rows[0][c]) !== String(row[c]),
        );
        throw new Error(
          `${table}: existing row ${row[keyColumn]} conflicts but differs in ${diffs.join(', ')}`,
        );
      }
      skippedPreProvisioned += 1;
    }
  }

  if (skippedPreProvisioned > 0) {
    log(
      `  ${table}: ${skippedPreProvisioned} row(s) already provisioned identically by the migration chain`,
    );
  }
}

/**
 * The primary key column(s) of a table, so verification can address a row by its real identity.
 *
 * Assuming `id` is not good enough: `authorization_functions` is keyed by `function_code` and
 * `authorization_role_functions` is a composite. A verification that assumes `id` fails to find those
 * rows and reports every one of them as missing — a false alarm loud enough to hide a real one.
 */
async function primaryKeyOf(client, ref) {
  const { schema, name } = splitQualified(ref);
  const { rows } = await client.query(
    `SELECT a.attname AS column_name
       FROM pg_index i
       JOIN pg_class c ON c.oid = i.indrelid
       JOIN pg_namespace n ON n.oid = c.relnamespace
       JOIN pg_attribute a ON a.attrelid = c.oid AND a.attnum = ANY(i.indkey)
      WHERE i.indisprimary AND n.nspname = $1 AND c.relname = $2
      ORDER BY array_position(i.indkey, a.attnum)`,
    [schema, name],
  );
  return rows.map((r) => r.column_name);
}

async function main() {
  requireDisposableCluster();
  const stamp = new Date().toISOString().replace(/[:.]/g, '-');
  const backupDir = path.join(BACKUP_ROOT, stamp);
  fs.mkdirSync(backupDir, { recursive: true });

  const sourceDb = ADMIN.database;
  const restoreDb = `${sourceDb}_restore_drill`;

  log(`backup-restore drill: ${sourceDb} -> ${backupDir}`);

  // ---------------------------------------------------------------- 1. backup
  const source = await connect(sourceDb);
  const manifest = { stamp, sourceDb, tables: {}, categories: {}, backupRoot: backupDir };

  for (const category of CATEGORIES) {
    manifest.categories[category.name] = [];
    for (const table of category.tables) {
      const { columns, rows } = await readTable(source, table);
      const bytes = writeTable(backupDir, table, { columns, rows });
      manifest.tables[table] = { count: rows.length, bytes, columns: columns.length };
      manifest.categories[category.name].push({ table, count: rows.length });
    }
  }

  manifest.protected = [];
  for (const name of PROTECTED_TABLES) {
    const ref = `protected_authority.${name}`;
    const { columns, rows } = await readTable(source, ref);
    const bytes = writeTable(backupDir, ref, { columns, rows });
    manifest.tables[ref] = { count: rows.length, bytes, columns: columns.length, protected: true };
    manifest.protected.push({ table: ref, count: rows.length });
  }

  manifest.supporting = [];
  for (const table of SUPPORTING) {
    const { columns, rows } = await readTable(source, table);
    const bytes = writeTable(backupDir, table, { columns, rows });
    manifest.tables[table] = {
      count: rows.length,
      bytes,
      columns: columns.length,
      supporting: true,
    };
    manifest.supporting.push({ table, count: rows.length });
  }
  fs.writeFileSync(path.join(backupDir, 'manifest.json'), JSON.stringify(manifest, null, 2));

  const allTables = [...CATEGORIES.flatMap((c) => c.tables), ...SUPPORTING];
  const totalRows = Object.values(manifest.tables).reduce((sum, t) => sum + t.count, 0);
  log(
    `backed up ${Object.keys(manifest.tables).length} tables (${
      allTables.length
    } public + ${PROTECTED_TABLES.length} protected) across ${CATEGORIES.length} categories`,
  );
  log(`total rows backed up: ${totalRows}`);

  const emptyCategories = Object.entries(manifest.categories)
    .filter(([, tables]) => tables.every((t) => t.count === 0))
    .map(([name]) => name);
  if (emptyCategories.length > 0) {
    log(`NOTE: no rows in categories: ${emptyCategories.join(', ')}`);
  }
  await source.end();

  // ---------------------------------------------------------------- 2. restore
  const admin = await connect('postgres');
  await admin.query(`DROP DATABASE IF EXISTS "${restoreDb}"`);
  await admin.query(`CREATE DATABASE "${restoreDb}"`);
  await admin.end();
  log(`created empty database ${restoreDb}`);

  execFileSync(
    'npx',
    [
      'ts-node',
      '--transpile-only',
      'node_modules/typeorm/cli.js',
      'migration:run',
      '-d',
      'src/config/data-source.ts',
    ],
    {
      cwd: path.join(__dirname, '..'),
      stdio: ['ignore', 'ignore', 'pipe'],
      env: { ...process.env, DB_NAME: restoreDb, APP_VERSION: 'backup-drill' },
    },
  );
  log('schema applied to restore target from the migration chain');

  const target = await connect(restoreDb);

  /*
   * ---------------------------------------------------------------------------------------------
   * Data is loaded with user triggers disabled, and that is a deliberate, load-bearing decision.
   * ---------------------------------------------------------------------------------------------
   *
   * The guards in this schema are written for *operations*, not for restores. Three of them made that
   * explicit when this drill first tried to replay them:
   *
   *   1. `institution_execution_evidence_guard` refuses unless `pg_trigger_depth() >= 2`. The row may
   *      only exist as a side effect of the lifecycle UPDATE that produced it. There is no sequence of
   *      statements a restore can issue to satisfy it.
   *   2. `approval_authority_guard` requires `d.expires_at > clock_timestamp()`. Every checker decision
   *      in a real backup is older than its expiry window — that is what expiry *means*. A restore three
   *      months after the fact could never reproduce a consumed approval, for the same reason a replay
   *      attack cannot. Re-pointing the expiry to make it pass would be falsifying governance evidence.
   *   3. `fn_financial_institution_guard` only accepts INSERT at 'REGISTERED', so a restored
   *      institution would have to be walked through a lifecycle that depends on (2).
   *
   * Postgres itself draws the same line: `pg_restore --disable-triggers` (and the `replica` role it
   * uses) exists precisely so that a restore reproduces *state* rather than re-running *policy*. Policy
   * was enforced when the rows were first written; a restore's obligation is to reproduce the resulting
   * state faithfully and then prove the state is sound.
   *
   * That trade is only acceptable because the proof is not skipped — it moves. With the guards silent,
   * the verification below has to establish integrity on its own evidence:
   *
   *   - every backed-up row is present and identical (counts plus content, not counts alone);
   *   - every foreign key in the restored data actually resolves (a full referential sweep, not a spot
   *     check on the two tables the mission names);
   *   - every ledger journal still balances, and the total debit across the whole ledger is unchanged;
   *   - every ledger line still points at its account and journal.
   *
   * A restore that bypassed the guards and then trusted them would prove nothing. One that bypasses
   * them and re-establishes the invariants from the data itself proves the thing that matters: the
   * backup carries enough information to reconstruct a database that is internally consistent.
   *
   * Operational consequence, stated plainly: this requires a role permitted to set
   * `session_replication_role`, i.e. a superuser. That is a deliberate narrowing of who may perform a
   * restore, and it is recorded as an outstanding deployment decision rather than assumed.
   */
  await target.query('SET session_replication_role = replica');
  log(
    'data load: user triggers disabled (session_replication_role=replica), as pg_restore --disable-triggers does',
  );

  /*
   * Pre-resolve identifier divergence BEFORE loading anything.
   *
   * Four migration-seeded ledger accounts are inserted with `gen_random_uuid()`:
   * 'CASH_TO_CASH-UNCLAIMED-NGN', 'AGENT_FUNDING_POOL-NGN', and the two commercial revenue/VAT
   * accounts. Verified across two independently migrated databases: the same `code`, different `id`
   * every time. (The payment settlement trio uses fixed `00000000-...-020{1,2,3}` ids and is stable.)
   *
   * The consequence for recovery is severe and silent. A backup taken from the source records ledger
   * lines pointing at the source's CASH_TO_CASH account. Restoring into a freshly migrated database
   * — the only kind that can accept the data — finds its own, differently-identified account under that
   * code. If the restore simply took the backup's id, the foreign key would fail; if it skipped the row,
   * the ledger lines would point at an account that no longer exists; if it adopted the target's id
   * without saying so, lines would silently re-attach to a *different account object* and no balance
   * would ever reveal it.
   *
   * This sweep finds every such collision in advance and records the mapping, so every later reference
   * can be rewritten deliberately and the whole set reported.
   */
  const tablePks = new Map();
  for (const ref of [...allTables, ...PROTECTED_TABLES.map((t) => `protected_authority.${t}`)]) {
    tablePks.set(ref, await primaryKeyOf(target, ref));
  }

  for (const ref of allTables) {
    const payload = JSON.parse(
      fs.readFileSync(path.join(backupDir, `${ref.replace(/\./g, '__')}.json`), 'utf8'),
    );
    if (payload.rows.length === 0) continue;
    const { schema, name } = splitQualified(ref);
    // Any unique key other than the primary key can cause an id divergence on reload.
    const { rows: uniques } = await target.query(
      `SELECT a.attname AS column_name
         FROM pg_index i
         JOIN pg_class c ON c.oid = i.indrelid
         JOIN pg_namespace n ON n.oid = c.relnamespace
         JOIN pg_attribute a ON a.attrelid = c.oid AND a.attnum = ANY(i.indkey)
        WHERE i.indisunique AND NOT i.indisprimary
          AND n.nspname = $1 AND c.relname = $2
          AND array_length(i.indkey, 1) = 1`,
      [schema, name],
    );
    for (const { column_name: uniqueColumn } of uniques) {
      for (const row of payload.rows) {
        const value = row[uniqueColumn];
        if (value === null || value === undefined) continue;
        const { rows: found } = await target.query(
          `SELECT "${tablePks.get(ref)[0] ?? 'id'}"::text AS target_id FROM "${schema}"."${name}" WHERE "${uniqueColumn}"::text = $1`,
          [String(value)],
        );
        if (found.length === 0) continue;
        const sourceId = String(row[tablePks.get(ref)[0] ?? 'id']);
        if (found[0].target_id === sourceId) continue;
        idRemaps.set(`${ref}:${sourceId}`, {
          table: ref,
          sourceId,
          targetId: found[0].target_id,
          column: uniqueColumn,
          value,
        });
      }
    }
  }

  if (idRemaps.size > 0) {
    log(
      `identifier divergence: ${idRemaps.size} migration-provisioned row(s) exist under the same ` +
        `business key with a different id; references will be re-pointed`,
    );
    for (const remap of idRemaps.values()) {
      log(
        `  ${remap.table} ${remap.column}=${remap.value}: ${remap.sourceId} -> ${remap.targetId}`,
      );
    }
  }

  const restoreStarted = Date.now();
  await target.query('BEGIN');

  const order = [...allTables];
  for (const ref of PROTECTED_TABLES) order.push(`protected_authority.${ref}`);

  let restoredRows = 0;
  for (const ref of order) {
    const file = path.join(backupDir, `${ref.replace(/\./g, '__')}.json`);
    const payload = JSON.parse(fs.readFileSync(file, 'utf8'));
    if (payload.rows.length === 0) continue;
    // Every uuid column except the primary key is treated as a possible reference. Narrowing this to
    // declared foreign keys would miss a self-referential or logically-linked column, and the cost of
    // being broad is a single lookup in a Map that is usually empty.
    const { schema, name } = splitQualified(ref);
    const { rows: uuidColumns } = await target.query(
      `SELECT column_name FROM information_schema.columns
        WHERE table_schema = $1 AND table_name = $2 AND data_type = 'uuid'`,
      [schema, name],
    );
    const pk = tablePks.get(ref) ?? [];
    const referencingColumns = uuidColumns.map((c) => c.column_name).filter((c) => !pk.includes(c));
    const { rows: remappedRows, rewritten } = applyRemaps(ref, payload.rows, referencingColumns);
    await restoreTable(target, ref, payload.columns, remappedRows);
    restoredRows += remappedRows.length;
    log(
      `  restored ${ref}: ${remappedRows.length} rows` +
        (rewritten > 0 ? ` (${rewritten} reference(s) re-pointed)` : ''),
    );
  }

  await target.query('COMMIT');
  await target.query('SET session_replication_role = origin');
  const restoreMs = Date.now() - restoreStarted;
  log(`restore complete in ${restoreMs}ms, ${restoredRows} rows`);
  log('user triggers re-enabled (session_replication_role=origin)');

  // ---------------------------------------------------------------- 3. verify
  const failures = [];
  const payloadOf = (ref) =>
    JSON.parse(fs.readFileSync(path.join(backupDir, `${ref.replace(/\./g, '__')}.json`), 'utf8'));

  /*
   * 3a. Every backed-up row present and identical, compared against the *source*, not against the
   * serialized backup.
   *
   * Comparing against the file looked reasonable and was subtly wrong: the file was produced by
   * `json_agg`, so a `timestamptz` arrives as a JSON string, while reading the restored row through the
   * driver yields a `Date`. Every timestamp column then "differs" and the drill reports hundreds of
   * false failures — noise that would bury a real one.
   *
   * Instead each row is fingerprinted by PostgreSQL on both sides with the *same* expression, so the
   * comparison is between two databases rather than between a database and a serializer. All of the
   * arithmetic stays server-side as well: `to_jsonb(numeric)` keeps the exact decimal, where parsing
   * the same value in JavaScript would silently round it to a double.
   */
  const verifier = await connect(sourceDb);
  await verifier.query("SET TIME ZONE 'UTC'");
  await target.query("SET TIME ZONE 'UTC'");

  /*
   * Columns excluded from the row comparison, and why each one is not evidence of a bad restore.
   *
   * `created_at` / `updated_at` / `inserted_at` — set by the migration that provisions a scheme row or
   * by a database default at insert time, so they record when the target was built, not what was backed
   * up.
   *
   * `effective_to` — `a2_finance_role_assignments` seeds `effective_to = now() + 1 year`. It is a
   * window computed at provisioning time, not stored history.
   *
   * Every other column, including every amount, balance, status, reason, digest and signature, must
   * match byte for byte. The exclusion list is deliberately short and named: a pattern such as
   * `%_at` would quietly excuse a settlement timestamp, which is exactly the kind of field that must
   * survive a restore unchanged.
   */
  const NON_RESTORED_COLUMNS = new Set(['created_at', 'updated_at', 'inserted_at', 'effective_to']);

  async function comparableJson(client, ref, extraExcluded = []) {
    const pk = await primaryKeyOf(client, ref);
    if (pk.length === 0) return null;
    const { schema, name } = splitQualified(ref);
    // Drop the non-restored columns with `-` on the jsonb document, which PostgreSQL evaluates
    // server-side; the surviving document keeps numeric precision instead of becoming a double.
    const excluded = new Set([...NON_RESTORED_COLUMNS, ...extraExcluded]);
    const strip = [...excluded].map((c) => `- '${c}'`).join(' ');
    const pkText = pk.map((c) => `"${c}"::text`).join(" || '|' || ");
    const { rows } = await client.query(
      `SELECT ${pkText} AS __pk, md5((to_jsonb(t) ${strip})::text) AS __hash
         FROM "${schema}"."${name}" t`,
    );
    const map = new Map();
    for (const row of rows) map.set(row.__pk, row.__hash);
    return map;
  }

  for (const ref of [...allTables, ...PROTECTED_TABLES.map((t) => `protected_authority.${t}`)]) {
    const payload = payloadOf(ref);
    if (payload.rows.length === 0) continue;
    // Identifiers that legitimately changed during this restore are compared under their target id,
    // and the identifier column itself is excluded from the content comparison — it is the one field
    // that is *supposed* to differ, and only for the rows this drill has already named.
    const remapForTable = new Map();
    for (const remap of idRemaps.values()) {
      if (remap.table === ref) remapForTable.set(remap.sourceId, remap.targetId);
    }
    const identityExclusion = remapForTable.size > 0 ? await primaryKeyOf(target, ref) : [];
    const [srcPrint, dstPrint] = await Promise.all([
      comparableJson(verifier, ref, identityExclusion),
      comparableJson(target, ref, identityExclusion),
    ]);
    if (srcPrint === null || dstPrint === null) {
      failures.push(`${ref}: no primary key, cannot verify row identity`);
      continue;
    }
    /*
     * A row whose reference was re-pointed cannot hash-match its source copy, and that is correct: the
     * referenced identifier genuinely changed (the migration re-provisioned that account under a new
     * id). The comparison is therefore run twice — once normally, and once with every remapped column
     * excluded — and a row passes if EITHER form matches. A row that fails both is a real difference.
     *
     * Excluding the remapped column for *all* rows of the table, rather than only the affected ones,
     * cannot hide a defect elsewhere: the exclusion applies to one column, that column is enumerated in
     * the report, and every other column must still match exactly.
     */
    /*
     * Which columns to exclude in the loose comparison: this table's own remapped key, plus any column
     * that *references* a remapped row from another table.
     *
     * Both directions matter. `ledger_accounts` rows are themselves re-keyed (its own `id`). A
     * `ledger_lines` or `financial_commitments` row keeps its own identity but points at a re-keyed
     * account, so the changed value is in an ordinary foreign-key column, not the primary key. Handling
     * only the first case reported every such row as corrupt.
     */
    const excludedForThisTable = new Set();
    for (const remap of idRemaps.values()) {
      if (remap.table === ref) excludedForThisTable.add(remap.column);
    }
    if (idRemaps.size > 0) {
      const remappedIds = new Set([...idRemaps.values()].map((r) => r.sourceId));
      const { schema: refSchema, name: refName } = splitQualified(ref);
      const { rows: fkColumns } = await target.query(
        `SELECT con.conname, a.attname AS column_name, pc.relname AS parent_table
           FROM pg_constraint con
           JOIN pg_class tc ON tc.oid = con.conrelid
           JOIN pg_class pc ON pc.oid = con.confrelid
           JOIN pg_namespace n ON n.oid = tc.relnamespace
           JOIN pg_attribute a ON a.attrelid = con.conrelid AND a.attnum = con.conkey[1]
          WHERE con.contype = 'f' AND n.nspname = $1 AND tc.relname = $2`,
        [refSchema, refName],
      );
      for (const fk of fkColumns) {
        const parentRemaps = [...idRemaps.values()].filter(
          (r) => r.table === fk.parent_table && remappedIds.has(r.sourceId),
        );
        if (parentRemaps.length > 0) excludedForThisTable.add(fk.column_name);
      }
    }
    const remapExclusions = [...excludedForThisTable];
    let srcLoose = null;
    let dstLoose = null;
    if (remapExclusions.length > 0) {
      [srcLoose, dstLoose] = await Promise.all([
        comparableJson(verifier, ref, [...identityExclusion, ...remapExclusions]),
        comparableJson(target, ref, [...identityExclusion, ...remapExclusions]),
      ]);
    }
    let altered = 0;
    let matched = 0;
    let matchedViaRemap = 0;
    for (const [pkValue, hash] of srcPrint) {
      const destinationKey = remapForTable.get(pkValue) ?? pkValue;
      if (dstPrint.has(destinationKey) && dstPrint.get(destinationKey) === hash) {
        matched += 1;
        continue;
      }
      if (srcLoose !== null && dstLoose !== null) {
        const looseSrc = srcLoose.get(pkValue);
        const looseDst = dstLoose.get(destinationKey);
        if (looseSrc !== undefined && looseSrc === looseDst) {
          matchedViaRemap += 1;
          continue;
        }
      }
      altered += 1;
    }
    if (matchedViaRemap > 0) {
      log(
        `  ${ref}: ${matchedViaRemap} row(s) matched after re-pointing ${remapExclusions.join(', ')} ` +
          `(the only columns allowed to differ)`,
      );
    }
    if (altered > 0) {
      failures.push(
        `${ref}: ${altered} of ${srcPrint.size} row(s) missing or altered after restore`,
      );
    } else {
      log(
        `  ${ref}: ${matched}/${srcPrint.size} rows identical after restore` +
          (matchedViaRemap > 0
            ? ` (${matchedViaRemap} via declared re-pointing)`
            : ' (byte-identical)'),
      );
    }
  }
  await verifier.end();

  // 3b. Full referential sweep. The guards were disabled during load, so nothing else has established
  // that the restored data is referentially sound.
  const fks = await target.query(
    `SELECT tc.relname AS child, pc.relname AS parent,
            a.attname AS column_name, pa.attname AS parent_column
       FROM pg_constraint con
       JOIN pg_class tc ON tc.oid = con.conrelid
       JOIN pg_class pc ON pc.oid = con.confrelid
       JOIN pg_namespace n ON n.oid = tc.relnamespace
       JOIN pg_attribute a ON a.attrelid = con.conrelid AND a.attnum = con.conkey[1]
      JOIN pg_attribute pa ON pa.attrelid = con.confrelid AND pa.attnum = con.confkey[1]
      WHERE con.contype = 'f' AND n.nspname = 'public'
        AND array_length(con.conkey, 1) = 1
        AND array_length(con.confkey, 1) = 1
        AND tc.relname = ANY($1)`,
    [allTables],
  );
  let brokenRefs = 0;
  for (const fk of fks.rows) {
    const result = await target.query(
      `SELECT count(*)::int AS n FROM "${fk.child}" c
        WHERE c."${fk.column_name}" IS NOT NULL
          AND NOT EXISTS (
            SELECT 1 FROM "${fk.parent}" p
             WHERE p."${fk.parent_column}" = c."${fk.column_name}"
          )`,
    );
    if (result.rows[0].n > 0) {
      brokenRefs += result.rows[0].n;
      failures.push(
        `${fk.child}.${fk.column_name}: ${result.rows[0].n} row(s) reference a missing ${fk.parent}`,
      );
    }
  }
  log(
    `referential sweep: ${fks.rows.length} foreign keys checked, ${brokenRefs} broken reference(s)`,
  );

  // 3c. Financial integrity.
  const unbalanced = await target.query(
    `SELECT j.id::text AS id
       FROM ledger_journals j JOIN ledger_lines l ON l.journal_id = j.id
      GROUP BY j.id
      HAVING SUM(CASE WHEN l.direction='DEBIT' THEN l.amount_minor ELSE -l.amount_minor END) <> 0`,
  );
  if (unbalanced.rows.length > 0) {
    failures.push(`${unbalanced.rows.length} unbalanced journal(s) after restore`);
  }

  const orphanLines = await target.query(
    `SELECT count(*)::int AS n FROM ledger_lines l
      WHERE NOT EXISTS (SELECT 1 FROM ledger_accounts a WHERE a.id = l.ledger_account_id)
         OR NOT EXISTS (SELECT 1 FROM ledger_journals j WHERE j.id = l.journal_id)`,
  );
  if (orphanLines.rows[0].n > 0) {
    failures.push(`${orphanLines.rows[0].n} orphaned ledger line(s) after restore`);
  }

  const sourceTotals = await connect(sourceDb);
  const [srcSum, rstSum] = await Promise.all([
    sourceTotals.query(
      `SELECT COALESCE(SUM(CASE WHEN direction='DEBIT' THEN amount_minor ELSE 0 END),0)::text AS debit,
              count(*)::int AS lines FROM ledger_lines`,
    ),
    target.query(
      `SELECT COALESCE(SUM(CASE WHEN direction='DEBIT' THEN amount_minor ELSE 0 END),0)::text AS debit,
              count(*)::int AS lines FROM ledger_lines`,
    ),
  ]);
  await sourceTotals.end();
  if (srcSum.rows[0].debit !== rstSum.rows[0].debit) {
    failures.push(
      `ledger debit total changed across restore: ${srcSum.rows[0].debit} -> ${rstSum.rows[0].debit}`,
    );
  }
  if (srcSum.rows[0].lines !== rstSum.rows[0].lines) {
    failures.push(
      `ledger line count changed across restore: ${srcSum.rows[0].lines} -> ${rstSum.rows[0].lines}`,
    );
  }

  const report = {
    stamp,
    totalRows,
    tables: Object.keys(manifest.tables).length,
    categories: Object.fromEntries(
      Object.entries(manifest.categories).map(([name, tables]) => [
        name,
        { tables: tables.length, rows: tables.reduce((sum, t) => sum + t.count, 0) },
      ]),
    ),
    emptyCategories,
    restoreMs,
    restoredRows,
    userTriggersDisabledDuringLoad: true,
    foreignKeysChecked: fks.rows.length,
    ledgerDebitTotal: rstSum.rows[0].debit,
    ledgerLines: rstSum.rows[0].lines,
    unbalancedJournals: unbalanced.rows.length,
    orphanedLines: orphanLines.rows[0].n,
    failures,
    restored: failures.length === 0,
  };
  fs.writeFileSync(path.join(backupDir, 'verification.json'), JSON.stringify(report, null, 2));
  log(JSON.stringify(report, null, 2));

  // A category with no rows was not exercised. Reporting it as "verified" because its tables came back
  // empty would be the same class of overstatement as claiming 166/166 when four files ran separately.
  const exercised = CATEGORIES.filter((c) => (report.categories[c.name]?.rows ?? 0) > 0).length;
  log(
    `categories exercised: ${exercised}/${CATEGORIES.length}` +
      (emptyCategories.length > 0
        ? ` (not exercised in this run: ${emptyCategories.join(', ')})`
        : ' (all eleven carried data)'),
  );

  await target.end();

  if (!process.argv.includes('--keep')) {
    const cleanup = await connect('postgres');
    await cleanup.query(`DROP DATABASE IF EXISTS "${restoreDb}"`);
    await cleanup.end();
    log('restore target dropped (use --keep to inspect it)');
  }

  if (failures.length > 0) {
    process.stderr.write(`BACKUP RESTORE FAILED: ${failures.join('; ')}\n`);
    process.exitCode = 1;
  } else {
    log('BACKUP RESTORE VERIFIED');
  }
}

main().catch((error) => {
  process.stderr.write(`backup-restore drill error: ${error.stack || error}\n`);
  // An open client with no pending work keeps the event loop alive, so a failed run that leaves one
  // would hang instead of exiting non-zero. Exit explicitly: a drill that cannot finish has failed.
  process.exit(1);
});
