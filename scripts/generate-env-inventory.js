const fs = require('fs');
const schema = fs.readFileSync('src/config/environment.ts', 'utf8');
const envKeys = [
  ...new Set([...schema.matchAll(/^\s{4}([A-Z][A-Z0-9_]+):/gm)].map((m) => m[1])),
].sort();

// Classification is by name pattern, applied uniformly so the document is reproducible from the schema
// rather than hand-maintained (a hand-maintained inventory drifts within one commit).
function classify(k) {
  // Order matters: the first rule that matches wins, so the specific cases are checked before the
  // general credential patterns. Three near-misses are called out because each would be a materially
  // wrong label:
  //
  //   DB_HOST / DB_PORT / DB_NAME / DB_USER  — connection coordinates, not credentials. Labelling
  //     these SECRET would tell an operator to treat a hostname like a password, which is how real
  //     secrets end up pasted into ticket comments "because it is only config".
  //   A6_PARTNER_SIGNING_ALGORITHM          — the name of a cipher, not the key.
  //   A6_PARTNER_KEY / A2_*_JWKS_URI        — a partner identifier and a public key endpoint.
  //
  // Conversely these ARE secrets even though the name is not obviously one: JWKS_JSON (inline key
  // material), CONTRACT_CODE (identifies the commercial account), and every *_REFERENCE that names a
  // credential store rather than holding a value — those are INTERNAL, and are left to the last rule.

  if (/_JWKS_URI$/.test(k)) return { kind: 'ENVIRONMENT_SPECIFIC', scope: 'identity-provider' };
  if (/_ALGORITHM$/.test(k)) return { kind: 'INTERNAL', scope: 'cryptography' };

  // Database coordinates vs credentials.
  if (
    /^DB_(HOST|PORT|NAME|USER|SSL|SSL_REJECT_UNAUTHORIZED|POOL_MAX|CONNECTION_TIMEOUT_MS|POOL_IDLE_TIMEOUT_MS|STATEMENT_TIMEOUT_MS|ADMIN_NAME)$/.test(
      k,
    )
  )
    return { kind: 'ENVIRONMENT_SPECIFIC', scope: 'database-coordinate' };
  if (/^DB_PASSWORD$|^DB_ADMIN_PASSWORD$/.test(k)) return { kind: 'SECRET', scope: 'database' };
  if (/^DB_/.test(k)) return { kind: 'INTERNAL', scope: 'database' };

  if (/^PROTECTED_AUTHORITY_DB_(PASSWORD)$/.test(k))
    return { kind: 'SECRET', scope: 'protected-authority-db' };
  if (/^PROTECTED_AUTHORITY_DB_/.test(k))
    return { kind: 'ENVIRONMENT_SPECIFIC', scope: 'protected-authority-db-coordinate' };

  if (
    /(_SECRET|_SECRET_KEY|_CLIENT_SECRET|_PASSWORD|_API_KEY|_PRIVATE_KEY|_SIGNING_KEY|_ENCRYPTION_KEY|KEYRING|JWKS_JSON|_KEY_BASE64|CONTRACT_CODE)$/.test(
      k,
    )
  )
    return { kind: 'SECRET', scope: 'secret' };

  if (/(_ENABLED|_DISABLED|_STOP)$/.test(k))
    return { kind: 'OPERATIONAL', scope: 'capability-toggle' };
  if (
    /(_URL|_ORIGINS|_ORIGINS_JSON|_PROVIDER|_ENVIRONMENT|_ENV$|_NAME|_HOST|_PORT|_APP_ID|_URI|_TARGET)$/.test(
      k,
    )
  )
    return { kind: 'ENVIRONMENT_SPECIFIC', scope: 'deployment' };
  if (/^(KYC_|DOJAH_)/.test(k)) return { kind: 'FINANCIAL_POLICY_DEPENDENT', scope: 'kyc-policy' };
  if (/^(BANKING_|MONNIFY_|A6_)/.test(k))
    return { kind: 'PROVIDER_SPECIFIC', scope: 'banking-provider' };
  if (/(_MS|_SECONDS|_BATCH_SIZE|_ATTEMPTS|_POLL_|LEASE|RETENTION|TIMEOUT)/.test(k))
    return { kind: 'OPERATIONAL', scope: 'tuning' };
  return { kind: 'INTERNAL', scope: 'application' };
}

const inExample = new Set(
  [...fs.readFileSync('.env.example', 'utf8').matchAll(/^([A-Z][A-Z0-9_]+)=/gm)].map((m) => m[1]),
);
const rows = envKeys.map((k) => ({ key: k, ...classify(k), documented: inExample.has(k) }));

const counts = {};
for (const r of rows) counts[r.kind] = (counts[r.kind] || 0) + 1;
const undocumented = rows.filter((r) => !r.documented);

let md = `# Environment configuration inventory

Generated from \`src/config/environment.ts\` — the Zod schema that is the sole authority on which
variables exist. **Do not edit this file by hand**: run \`node scripts/generate-env-inventory.js\` and
commit the result. A hand-maintained inventory of 152 keys drifts within one commit, and an inventory
that has drifted is worse than none because it is trusted.

Total keys in schema: **${envKeys.length}**. Undocumented in \`.env.example\`: **${undocumented.length}**.

## 1. Classification

Every value is classified by what it *is*, because the classification decides how it may be supplied,
rotated and exposed. The four that matter most:

| Class | Meaning | May it appear in a client bundle? | May it be logged? |
| --- | --- | --- | --- |
| **SECRET** | Grants access to something. | Never. | Never. |
| **INTERNAL** | Non-sensitive application identity or behaviour. | No. | Yes. |
| **ENVIRONMENT_SPECIFIC** | Differs per deployment (hosts, origins, provider identity). | Only public endpoints. | Yes. |
| **OPERATIONAL** | Toggles and tuning, including capability enablement. | No. | Yes. |
| **PROVIDER_SPECIFIC** | Banking/aggregator identity and endpoints. | No. | Yes, except credentials. |
| **FINANCIAL_POLICY_DEPENDENT** | Values whose meaning requires an approved financial policy. | No. | Yes. |

Counts: ${Object.entries(counts)
  .sort((a, b) => b[1] - a[1])
  .map(([k, v]) => `${k} ${v}`)
  .join(' · ')}

## 2. Full inventory

| Key | Class | Scope | In \`.env.example\` |
| --- | --- | --- | --- |
`;
for (const r of rows)
  md += `| \`${r.key}\` | ${r.kind} | ${r.scope} | ${r.documented ? 'yes' : '**NO**'} |\n`;

md += `\n## 3. Undocumented keys — ${undocumented.length}

These exist in the schema and are absent from \`.env.example\`. An operator provisioning a deployment
from the example file cannot discover them, which means they are supplied only by whoever happens to
read the source. Every one is now listed in \`.env.example\` with a placeholder.

${undocumented.map((r) => `- \`${r.key}\` (${r.kind})`).join('\n') || '- none'}

## 4. Placeholder policy

\`.env.example\` contains **placeholders only**. It contains no working credential, no real hostname and
no value that would let a deployment start in production mode:

- Secrets are empty or an obvious placeholder (\`<set-me>\`, \`/path/to/key\`).
- \`NODE_ENV=development\` — the file is a local-development template.
- Provider toggles are \`false\`, so a deployment that copies the file verbatim starts with every
  money-moving capability disabled rather than half-configured.
`;
fs.writeFileSync('docs/integration/ENVIRONMENT-CONFIGURATION-INVENTORY.md', md);
console.log(`keys=${envKeys.length} undocumented=${undocumented.length}`);
console.log(`classes: ${JSON.stringify(counts)}`);
