#!/usr/bin/env node
'use strict';

/**
 * Prepares the local, git-ignored `.env` used by the real-PostgreSQL integration suites
 * (`npm run test:pg`) and the embedded PostgreSQL server (`node scripts/embedded-pg.js`).
 *
 * Why this exists (ARENA 3, PostgreSQL regression triage 2026-10-26):
 *   A large family of integration suites (V1-ADMIN-LOCAL-LOGIN-01, V1-ADMIN-AUTHORIZATION-*,
 *   V1-ADMINISTRATOR-ROLE-AND-ASSIGNMENT-*, P0-A/P0-B governance suites, A22, ...) boots the
 *   REAL AppModule and deliberately does NOT override A2_WORKFORCE_CONFIG. They therefore
 *   require the documented local-development workforce configuration to be present in the
 *   environment: an enabled SUPER_ADMIN role in A2_FINANCE_ROLES_JSON, the three required
 *   maker-checker rules, and the four required rate-limit categories. Without it the suites
 *   fail closed with "SUPER_ADMIN role is disabled or undefined in configuration" or
 *   "Workforce authentication disabled" — an environment/configuration defect, not an
 *   application defect.
 *
 *   `.env.example` documents the local-dev block but (a) keeps it commented out and (b) its
 *   commented A2_FINANCE_ROLES_JSON predates V1-ADMINISTRATOR-ROLE-AND-ASSIGNMENT-01 and only
 *   carries four of the five required roles. The authoritative five-role vocabulary lives in
 *   docs/deployment/config/v1-workforce-bootstrap.env.template. This script composes a
 *   working test `.env` from those two committed sources so every engineer/agent reproduces
 *   the same configuration. No secret material: every value is a committed public placeholder.
 *
 * Usage:
 *   node scripts/prepare-pg-test-env.js           # refuses to overwrite an existing .env
 *   node scripts/prepare-pg-test-env.js --force   # regenerate even if .env exists
 */

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const ENV_EXAMPLE = path.join(ROOT, '.env.example');
const BOOTSTRAP_TEMPLATE = path.join(
  ROOT,
  'docs',
  'deployment',
  'config',
  'v1-workforce-bootstrap.env.template',
);
const ENV_TARGET = path.join(ROOT, '.env');

function readKeysFromTemplate(file, keys) {
  const out = new Map();
  for (const line of fs.readFileSync(file, 'utf8').split('\n')) {
    const trimmed = line.replace(/^#\s?/, '');
    const match = /^([A-Z0-9_]+)=(.*)$/.exec(trimmed.trim());
    if (match && keys.includes(match[1]) && !out.has(match[1])) {
      out.set(match[1], match[2]);
    }
  }
  return out;
}

function main() {
  const force = process.argv.includes('--force');
  if (fs.existsSync(ENV_TARGET) && !force) {
    console.error(
      `Refusing to overwrite existing ${ENV_TARGET}. Re-run with --force to regenerate.`,
    );
    process.exit(1);
  }
  if (!fs.existsSync(ENV_EXAMPLE)) {
    console.error(`Missing ${ENV_EXAMPLE}`);
    process.exit(1);
  }
  if (!fs.existsSync(BOOTSTRAP_TEMPLATE)) {
    console.error(`Missing ${BOOTSTRAP_TEMPLATE}`);
    process.exit(1);
  }

  // Authoritative workforce configuration keys, taken verbatim from the committed
  // bootstrap template (five-role vocabulary incl. ADMINISTRATOR, maker-checker rules,
  // rate limits, local-dev OIDC placeholders).
  const workforceKeys = [
    'A2_WORKFORCE_ENABLED',
    'A2_WORKFORCE_OIDC_ISSUER',
    'A2_WORKFORCE_OIDC_JWKS_URI',
    'A2_WORKFORCE_OIDC_AUDIENCE',
    'A2_WORKFORCE_OIDC_CLIENT_ID',
    'A2_FINANCE_ROLES_JSON',
    'A2_MAKER_CHECKER_RULES_JSON',
    'A2_WORKFORCE_RATE_LIMITS_JSON',
  ];
  const overrides = readKeysFromTemplate(BOOTSTRAP_TEMPLATE, workforceKeys);
  for (const key of workforceKeys) {
    if (!overrides.has(key)) {
      console.error(`Bootstrap template does not define ${key}; aborting.`);
      process.exit(1);
    }
  }
  // Keep the safe fail-closed defaults for everything the template does not cover:
  // bootstrap/recovery ceremonies stay DISABLED for plain integration runs.

  // Local embedded PostgreSQL credentials (scripts/embedded-pg.js) — not secrets.
  const dbOverrides = {
    DB_HOST: '127.0.0.1',
    DB_PORT: '5432',
    DB_NAME: 'monienaija',
    DB_USER: 'monienaija',
    DB_PASSWORD: 'monienaija-pw',
    DB_SSL: 'false',
  };

  const lines = fs.readFileSync(ENV_EXAMPLE, 'utf8').split('\n');
  const seen = new Set();
  const out = lines.map((line) => {
    const match = /^([A-Z0-9_]+)=(.*)$/.exec(line.trim());
    if (!match) return line;
    const [, key] = match;
    const value = overrides.has(key)
      ? overrides.get(key)
      : Object.prototype.hasOwnProperty.call(dbOverrides, key)
        ? dbOverrides[key]
        : match[2];
    seen.add(key);
    return `${key}=${value}`;
  });

  for (const [key, value] of [...overrides, ...Object.entries(dbOverrides)]) {
    if (!seen.has(key)) out.push(`${key}=${value}`);
  }

  out.unshift(
    '# Generated by scripts/prepare-pg-test-env.js from .env.example +',
    '# docs/deployment/config/v1-workforce-bootstrap.env.template (public placeholders only).',
    '# Local integration-test configuration for the embedded PostgreSQL harness. Never commit.',
  );

  fs.writeFileSync(ENV_TARGET, out.join('\n'));
  console.log(`Wrote ${ENV_TARGET} (workforce roles/rules/rate-limits enabled, embedded-PG DB credentials).`);
}

main();
