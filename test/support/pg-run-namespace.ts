/**
 * Run-scoped database namespace for the real-PostgreSQL integration harness.
 *
 * Every integration-test run must carry a validated, run-specific identifier
 * (`PG_TEST_RUN_ID`) that is embedded in every generated database name. This guarantees a new
 * run can never collide with databases left behind by previous runs (for example when the OS
 * reuses a process id), and that every cleanup operation only ever targets databases created
 * under the CURRENT run's namespace. Databases from older naming schemes or other runs (e.g.
 * `mn_it_h04unify_20364`) are structurally unreachable: they cannot be generated, and the
 * drop helpers refuse any name outside the current namespace.
 *
 * The identifier is resolved ONCE per process and memoised, so every suite and every cleanup
 * operation in the same run uses exactly the same namespace even if the environment is
 * mutated mid-run. It is never invented by the harness when missing and never silently
 * downgraded to the old un-namespaced scheme: a missing or invalid identifier fails loudly
 * with remediation guidance. `npm run test:pg` generates (or validates) the identifier once
 * for the whole run and propagates it to every batch process.
 */

export const PG_TEST_RUN_ID_ENV = 'PG_TEST_RUN_ID';

/**
 * Safe identifier grammar for the run id (also enforced by scripts/run-pg-integration-tests.js
 * — keep the two in sync): starts with a letter, lowercase alphanumeric only, 4-16 chars.
 * Bounded so generated database names stay well inside PostgreSQL's 63-byte identifier limit.
 */
export const RUN_IDENTIFIER_PATTERN = /^[a-z][a-z0-9]{3,15}$/;

const REMEDIATION =
  `Run the suites via "npm run test:pg" (which generates one and propagates it to every ` +
  `batch process), or set ${PG_TEST_RUN_ID_ENV} to a validated identifier such as ` +
  `"win21oct" (pattern ${String(RUN_IDENTIFIER_PATTERN)}). The harness never falls back ` +
  `to un-namespaced database names.`;

export function isValidRunIdentifier(value: unknown): value is string {
  return typeof value === 'string' && RUN_IDENTIFIER_PATTERN.test(value);
}

/** Validates a run identifier, returning it unchanged, or throws with remediation guidance. */
export function validateRunIdentifier(value: string): string {
  if (!isValidRunIdentifier(value)) {
    throw new Error(
      `Invalid ${PG_TEST_RUN_ID_ENV} ${JSON.stringify(value)}: must match ` +
        `${String(RUN_IDENTIFIER_PATTERN)}. ${REMEDIATION}`,
    );
  }
  return value;
}

let memoizedRunIdentifier: string | undefined;

/**
 * The run identifier for this process: validated from `PG_TEST_RUN_ID`, memoised on first
 * resolution so every suite and cleanup operation in the run shares one namespace. Throws
 * when the identifier is missing or invalid — deliberately NOT a silent fallback to the old
 * `mn_it_<label>_<pid>` naming scheme.
 */
export function resolveRunIdentifier(): string {
  if (memoizedRunIdentifier !== undefined) return memoizedRunIdentifier;
  const raw = process.env[PG_TEST_RUN_ID_ENV];
  if (raw === undefined || raw === '') {
    throw new Error(
      `${PG_TEST_RUN_ID_ENV} is required for integration-test database naming (run namespace). ` +
        REMEDIATION,
    );
  }
  memoizedRunIdentifier = validateRunIdentifier(raw);
  return memoizedRunIdentifier;
}

/** Test-only: clears the memo so unit tests can exercise each identifier path in isolation. */
export function resetRunIdentifierMemoForTests(): void {
  memoizedRunIdentifier = undefined;
}

/**
 * Cleanup scoping guard: asserts a database name belongs to the CURRENT run's namespace
 * (generated by this run's naming scheme with this run's identifier and process id). Cleanup
 * helpers must call this before any DROP so a pre-existing or foreign database — e.g.
 * `mn_it_h04unify_20364` — can never be dropped by a new run.
 */
export function assertOwnRunDatabaseName(name: string): void {
  const runId = resolveRunIdentifier();
  const suffix = `_${runId}_${process.pid}`;
  if (!name.startsWith('mn_it_') || !name.endsWith(suffix)) {
    throw new Error(
      `Refusing to operate on database ${JSON.stringify(name)}: it is outside this run's ` +
        `namespace (expected names like "mn_it_<label>${suffix}" or "mn_it_tpl${suffix}"). ` +
        `Only databases created by the current run may be dropped.`,
    );
  }
}
