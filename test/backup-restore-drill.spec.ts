import { readFileSync } from 'node:fs';
import { join } from 'node:path';

/**
 * Guards for `scripts/backup-restore-drill.js`.
 *
 * The drill itself needs a live PostgreSQL cluster and is executed out of band. What is checked here are
 * the properties that make running it safe and make its result meaningful — the ones that would be
 * silently lost in a well-intentioned refactor. Each assertion below corresponds to a failure that
 * actually occurred while the drill was being written, so removing the corresponding code would
 * reintroduce a real defect rather than merely break a test.
 */
const DRILL = readFileSync(join(__dirname, '..', 'scripts', 'backup-restore-drill.js'), 'utf8');

describe('backup/restore drill', () => {
  it('refuses to run without an explicit disposable-cluster confirmation', () => {
    expect(DRILL).toContain('PG_TEST_CONFIRM_DISPOSABLE_CLUSTER');
    expect(DRILL).toMatch(/PG_TEST_CONFIRM_DISPOSABLE_CLUSTER !== 'yes'/);
    // The check must run before anything that could create or drop a database.
    const guardIndex = DRILL.indexOf('PG_TEST_CONFIRM_DISPOSABLE_CLUSTER !==');
    const createIndex = DRILL.indexOf('CREATE DATABASE');
    expect(guardIndex).toBeGreaterThan(-1);
    expect(createIndex).toBeGreaterThan(guardIndex);
  });

  it('encodes numerics as exact decimal text rather than through JSON numbers', () => {
    // JSON.parse turns a bare JSON number into a double; a ledger amount of 20 significant digits does
    // not survive that. The projection must cast these types to text inside SQL.
    expect(DRILL).toMatch(/\['numeric', 'bigint'\]\.includes\(type\)/);
    expect(DRILL).toContain('::text AS');
  });

  it('stringifies jsonb columns so an empty array does not restore as an empty object', () => {
    // node-postgres serializes a JS array as a PostgreSQL array literal; the jsonb input function reads
    // `{}` as an object. `scopes: []` silently became `scopes: {}` before this was fixed.
    expect(DRILL).toContain('function bindValue');
    expect(DRILL).toMatch(/typeof value === 'object'.*JSON\.stringify\(value\)/s);
  });

  it('loads data in a single transaction so deferred ledger constraints can be satisfied at COMMIT', () => {
    const body = DRILL.slice(DRILL.indexOf('async function main()'));
    expect(body).toContain("await target.query('BEGIN')");
    expect(body).toContain("await target.query('COMMIT')");
    // The ledger balance triggers are DEFERRABLE INITIALLY DEFERRED: a journal is inserted before the
    // lines that balance it, and only becomes valid at COMMIT. Autocommit would reject every journal.
    expect(body.indexOf("'BEGIN'")).toBeLessThan(body.indexOf("'COMMIT'"));
  });

  it('backs up and restores the protected authority evidence, not only the public schema', () => {
    // Without checker_decisions and approval_consumptions a public-only backup cannot be restored at
    // all: the approval guard refuses any row lacking its matching evidence.
    expect(DRILL).toContain('PROTECTED_TABLES');
    expect(DRILL).toContain('checker_decisions');
    expect(DRILL).toContain('approval_consumptions');
  });

  it('does not silently copy tables that are regenerated by triggers', () => {
    // governed_institution_lifecycle_executions refuses INSERT unless pg_trigger_depth() >= 2; the
    // lifecycle replay regenerates it. Copying it is impossible as well as wrong.
    const categoryBlock = DRILL.slice(
      DRILL.indexOf('const CATEGORIES'),
      DRILL.indexOf('const PROTECTED_TABLES'),
    );
    expect(categoryBlock).not.toContain("'governed_institution_lifecycle_executions'");
    expect(DRILL).toContain('pg_trigger_depth');
    // kyc_evaluation_refresh is a derived work queue the KYC triggers repopulate during the restore.
    expect(DRILL).toContain('kyc_evaluation_refresh');
    expect(DRILL).toMatch(/Deliberately excluded: `kyc_evaluation_refresh`/);
  });

  it('resolves non-deterministic seed identifiers before loading dependent rows', () => {
    // Four ledger accounts are migration-seeded with gen_random_uuid(), so their ids differ between any
    // two databases. Dependent references are re-pointed up front, and the drift is reported.
    expect(DRILL).toContain('identifier divergence');
    expect(DRILL).toContain('gen_random_uuid');
    const divergenceIndex = DRILL.indexOf('identifier divergence');
    const loadIndex = DRILL.indexOf(
      'await restoreTable(target, ref, payload.columns, remappedRows)',
    );
    expect(loadIndex).toBeGreaterThan(-1);
    expect(divergenceIndex).toBeLessThan(loadIndex);
  });

  it('verifies every row against the live source rather than against the serialized file', () => {
    // Comparing against the file produced hundreds of false failures: a timestamptz is a JSON string in
    // the file and a Date from the driver. Both sides are now fingerprinted by PostgreSQL.
    expect(DRILL).toContain('comparableJson');
    expect(DRILL).toMatch(/md5\(\(to_jsonb\(t\)/);
    expect(DRILL).not.toMatch(/sameExceptTimestamps\(payload\.columns, found\.rows\[0\], row\)/);
  });

  it('proves referential and financial integrity after the guards were bypassed during load', () => {
    // The load runs with session_replication_role = replica, so nothing else has established that the
    // restored data is sound. These checks are what pay for that.
    expect(DRILL).toContain('SET session_replication_role = replica');
    expect(DRILL).toContain('SET session_replication_role = origin');
    expect(DRILL).toContain('referential sweep');
    expect(DRILL).toMatch(/unbalanced journal/i);
    expect(DRILL).toMatch(/orphaned ledger line/i);
    expect(DRILL).toContain('ledgerDebitTotal');
  });

  it('reports how many of the eleven categories actually carried data', () => {
    // A category with no rows was not exercised. Reporting it as verified would overstate the result in
    // exactly the way the mission forbids.
    expect(DRILL).toContain('categories exercised');
    expect(DRILL).toContain('not exercised in this run');
    expect(DRILL).toMatch(/emptyCategories/);
  });

  it('exits non-zero on failure instead of hanging', () => {
    // An open client with no pending work keeps the event loop alive; a failed run that left one hung
    // rather than reporting failure.
    expect(DRILL).toContain('process.exit(1)');
  });
});
